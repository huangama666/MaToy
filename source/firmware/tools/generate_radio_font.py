"""Generate the fixed radio UI and station-title font subsets."""
from pathlib import Path
import json
import sys
from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

project, font_path = map(Path, sys.argv[1:])
catalog = json.loads((project / 'assets/radio/stations.json').read_text())
source = (project / 'main/radio_ui.c').read_text() + (project / 'main/screen_app.c').read_text()
text = ''.join(c for c in source if '\u4e00' <= c <= '\u9fff')
text += ''.join(item['name'] + item['frequency'] for item in catalog['stations'])
text += ''.join(item['name'] for item in catalog['regions']) + '·'
codes = sorted(set(map(ord, text)) | set(range(32, 127)))
coverage = TTFont(font_path).getBestCmap()
missing = [f'U+{code:04X}' for code in codes if code not in coverage]
assert not missing, missing
fonts = {}
for size in (16, 20):
    fonts[size] = ImageFont.truetype(str(font_path), size)
    fonts[size].set_variation_by_name('SemiBold')

def rows(code, size):
    char = chr(code)
    width = size // 2 if code < 0x2e80 else size
    left, top, right, bottom = fonts[size].getbbox(char)
    render_width = max(width, right - left)
    image = Image.new('L', (render_width, size))
    ImageDraw.Draw(image).text(((render_width-right-left)//2, (size-bottom-top)//2), char, font=fonts[size], fill=255)
    if render_width > width:
        image = image.resize((width, size), Image.Resampling.LANCZOS)
    return [sum((image.getpixel((x, y)) >= 96) << (31-x) for x in range(width)) for y in range(size)]

header = """// Noto Serif SC SemiBold, SIL OFL. Generated by tools/generate_radio_font.py.
#pragma once

#include <stdint.h>

typedef struct {
    uint32_t codepoint;
    uint32_t small[16], large[20];
} radio_glyph_t;

static const radio_glyph_t radio_glyphs[] = {
"""
for code in codes:
    header += f'    {{0x{code:04x}, {{' + ','.join(f'0x{r:08x}' for r in rows(code,16)) + '}, {'
    header += ','.join(f'0x{r:08x}' for r in rows(code,20)) + '}},\n'
header += '};\n'
(project / 'main/radio_font.h').write_text(header)
print(len(codes), 'glyphs, source coverage verified')
